export function translator(locale: Locale): Translate {
  const messages = locale === 'en' ? en : ru
  return (key, values) => messages[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    values?.[name] === undefined ? placeholder : String(values[name])
  ))
}
